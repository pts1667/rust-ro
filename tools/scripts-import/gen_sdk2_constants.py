#!/usr/bin/env python3
"""Generates lib/script-sdk-2/src/constants.rs from the server's own script constant values.

The names are the constants the scripts look up at run time (`ctx.constant("JOB_NOVICE")`) or name directly
(`constants::JOB_NOVICE`).
Values come from the server: a unit test in `server/src/tests/script_constant_export_test.rs` resolves
each name through the same lookup the game uses, so the typed constants cannot drift from the server.
Names the server does not resolve are left out and stay on the run-time `ctx.constant` path.
"""

import argparse
import json
import os
import re
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPTS = ROOT / "scripts"
OUTPUT = ROOT / "lib/script-sdk-2/src/constants.rs"
EXPORT_TEST = "export_script_constant_values"
NAME_PATTERN = re.compile(r'\.constant\("([A-Za-z0-9_]+)"\)|constants::([A-Za-z0-9_]*[A-Za-z0-9])\b(?!\*)')
IMPORT_PATTERN = re.compile(r"constants::\{([^}]*)\}")


def collect_names() -> list[str]:
    names = set()
    sources = [path for path in SCRIPTS.rglob("*.rs") if "target" not in path.relative_to(SCRIPTS).parts]
    sources += [path for path in OUTPUT.parent.rglob("*.rs") if path != OUTPUT]
    for path in sources:
        text = path.read_text(encoding="utf-8", errors="replace")
        for match in NAME_PATTERN.finditer(text):
            names.add(match.group(1) or match.group(2))
        for match in IMPORT_PATTERN.finditer(text):
            names.update(name.strip() for name in match.group(1).split(",") if name.strip())
    return sorted(names)


def export_values(names: list[str], work_dir: Path) -> dict:
    names_file = work_dir / "constant_names.txt"
    values_file = work_dir / "constant_values.json"
    names_file.write_text("\n".join(names) + "\n", encoding="utf-8")
    env = dict(os.environ, SCRIPT_CONSTANT_NAMES=str(names_file), SCRIPT_CONSTANT_VALUES=str(values_file))
    command = ["cargo", "test", "--release", "--package", "server", "--features", "unit_tests", EXPORT_TEST]
    result = subprocess.run(command, cwd=ROOT, env=env, capture_output=True, text=True)
    if result.returncode != 0:
        raise SystemExit(f"constant export failed:\n{result.stdout}\n{result.stderr}")
    return json.loads(values_file.read_text(encoding="utf-8"))


def render(values: dict) -> str:
    lines = [
        "//! Script constants, as the server resolves them.",
        "//!",
        "//! Generated by `tools/scripts-import/gen_sdk2_constants.py`. Do not edit by hand.",
        "",
        "#![allow(non_upper_case_globals)]",
        "",
    ]
    for name in sorted(values):
        value = values[name]
        if isinstance(value, bool) or value is None:
            continue
        if isinstance(value, int):
            lines.append(f"pub const {name}: i32 = {value};")
        else:
            lines.append(f"pub const {name}: &str = {json.dumps(value)};")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the generated file is out of date instead of writing it")
    args = parser.parse_args()

    names = collect_names()
    with tempfile.TemporaryDirectory() as work:
        values = export_values(names, Path(work))
    unresolved = [name for name in names if values.get(name) is None]
    rendered = render(values)

    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != rendered:
            raise SystemExit(f"{OUTPUT} is out of date; run gen_sdk2_constants.py")
    else:
        OUTPUT.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"{len(names)} names, {len(names) - len(unresolved)} resolved, {len(unresolved)} unresolved")
    for name in unresolved:
        print(f"  unresolved: {name}")


if __name__ == "__main__":
    main()
