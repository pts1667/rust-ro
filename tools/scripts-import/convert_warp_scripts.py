#!/usr/bin/env python3
"""Lowers the NPCs that rathena's warp files write as scripts into the `towns_warps` module, and places them.

    python -I -X utf8 tools/scripts-import/convert_warp_scripts.py

`import_world_data.py` imports the plain `warp` lines of `npc/warps` and `npc/pre-re/warps`, and `convert_npcs.py` leaves
those sources out, so the warps written as scripts were missing: random warps (the maze in front of the Heart of Ymir in
`yuno_in05`, the Clock Tower and its basement, the Lighthalzen cubes), warps behind a condition (a level, a quest step)
and the NPCs around them. This lowers them as `convert_sdk2.py` lowers every other script, into
`scripts/towns/towns_warps/src`, and replaces the module's entries of `config/wasm/npcs.json` and `events.json`.

Two rules on top of the shared lowering keep `extract_npc_warps.py` able to see where they lead:
- A touch area without an `OnTouch` label runs the NPC's own script when walked into (the server clicks it). When that
  script opens no window, the NPC also gets an explicit `OnTouch` event, so the warp is listed as a touch.
- A `function script` of the shared crate the NPCs call (`randomw` of the cubes) is copied into the module, so its
  literal warps are found.

Run `extract_npc_warps.py` and `scripts-build` afterwards.
"""

import json
import pathlib
import re
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import convert_sdk2  # noqa: E402
from convert_npcs import conf_files  # noqa: E402
from rathena_script.codegen import Context  # noqa: E402
from rathena_script.emit import event_name  # noqa: E402
from rathena_script.names import load_names  # noqa: E402
from rathena_script.parser import parse_file  # noqa: E402
from rathena_script.sdk2 import Unsupported, fn_name, lower_script  # noqa: E402

ROOT = convert_sdk2.ROOT
MODULE = "towns_warps"
CRATE = ROOT / "scripts" / "towns" / MODULE
GENERATED = "// Generated by tools/scripts-import/convert_warp_scripts.py"
# Left out on purpose: the GM's arena switch (`F_GM_NPC`), which players never use
SKIPPED = {"#arenacontrol": "GM only"}
# A script that opens a window is talked to, even when walking into it opens it
WINDOW = re.compile(r"ctx\.(?:lines|lines_as|next|close_window|close)\b|select_values|Function::(?:Select|Menu|Mes)\b")
SHARED_CALL = re.compile(r"\bshared::(\w+)::(\w+)\(")


def world(rathena):
    """The lowering context every module is lowered with: the constants, and the shared functions `callfunc` reaches."""
    constants, parameters = load_names(rathena)
    parsed, converted = [], set()
    for module, sources in convert_sdk2.MODULES.items():
        for path in convert_sdk2.source_files(rathena, sources):
            relative = convert_sdk2.relative_path(rathena, path)
            converted.add(relative)
            parsed += [(relative, definition) for definition in parse_file(path, relative)]
    library = []
    for path, relative in convert_sdk2.library_files(rathena, converted):
        library += [(relative, definition) for definition in parse_file(path, relative)]
    exnames = {d.exname: d.name for _, d in parsed if d.exname and d.place is not None and d.kind in ("script", "duplicate")}
    _, callable = convert_sdk2.lower_library(parsed + library, constants, parameters, exnames)
    shared = {name: f"shared::{convert_sdk2.flat_name(relative)}::{fn_name(name)}" for name, relative in callable.items()}
    return Context(constants, parameters, shared, exnames)


def warp_definitions(rathena):
    """The script and duplicate NPCs of the warp files the pre-renewal chain loads, in load order."""
    definitions = []
    for source in (path for path in conf_files(rathena) if "/warps/" in path):
        base = rathena / source
        for path in [base] if base.is_file() else sorted(base.rglob("*.txt")):
            relative = convert_sdk2.relative_path(rathena, path)
            definitions += [(relative, d) for d in parse_file(path, relative) if d.kind in ("script", "duplicate") and not d.error and d.name]
    return definitions


def shared_function(module, name):
    """The source of `name` in the shared crate's `module`, found by its braces."""
    text = (ROOT / "scripts" / "shared" / "src" / f"{module}.rs").read_text(encoding="utf-8")
    start = re.search(rf"^pub fn {name}\b", text, re.MULTILINE)
    if start is None:
        raise ValueError(f"shared::{module}::{name} not found")
    depth, index = 0, text.index("{", start.start())
    for end in range(index, len(text)):
        depth += {"{": 1, "}": -1}.get(text[end], 0)
        if depth == 0:
            return text[start.start() : end + 1].replace("pub fn", "fn", 1)
    raise ValueError(f"shared::{module}::{name} has no end")


def inline_shared(files):
    """Copies the shared functions a file calls into it, when they call no other shared function."""
    for path, text in files.items():
        copied = {}
        for module, name in sorted(set(SHARED_CALL.findall(text))):
            source = shared_function(module, name)
            if SHARED_CALL.search(source):
                continue
            copied[name] = source
            text = text.replace(f"shared::{module}::{name}(", f"{name}(")
        if copied:
            files[path] = text.rstrip("\n") + "\n\n" + "\n\n".join(copied.values()) + "\n"
    return files


def main():
    rathena = ROOT.parent / "rathena"
    context = world(rathena)
    definitions = warp_definitions(rathena)
    scripts, routes, skipped = [], {}, []
    for relative, definition in definitions:
        if definition.kind != "script":
            continue
        if definition.name in SKIPPED:
            skipped.append(f"{definition.name} ({SKIPPED[definition.name]})")
            continue
        try:
            lowered = lower_script(definition, context, fn_name(definition.name))
        except Unsupported as reason:
            skipped.append(f"{definition.name} ({reason})")
            continue
        labels = [label for label, _ in lowered.events]
        touch = definition.trigger and definition.trigger != (0, 0)
        if touch and "OnTouch" not in labels and "OnTouch_" not in labels and not WINDOW.search("\n".join(lowered.items)):
            lowered.events.append(("OnTouch_", lowered.npc))
        routes[definition.name] = (definition, [label for label, _ in lowered.events])
        scripts.append((relative, definition.name, lowered))

    convert_sdk2.GENERATED = GENERATED
    files = inline_shared(convert_sdk2.render_module(scripts))
    files["lib.rs"] = files["lib.rs"].replace(
        f"{GENERATED}. Delete this line to stop the generator from overwriting the file.",
        f"{GENERATED}: the NPCs of rathena's warp files that are scripts. Delete this line to stop the generator from overwriting the file.",
    )
    source = CRATE / "src"
    for stale in source.rglob("*.rs"):
        stale.unlink()
    for relative, text in files.items():
        target = source / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    subprocess.run(["rustfmt", "--edition", "2021", *sorted(str(path) for path in source.rglob("*.rs"))], check=True)
    if "shared::" in "".join(files.values()):
        print("note: the module still calls the shared crate; it needs `shared.workspace = true`")

    npcs_path, events_path = ROOT / "config/wasm/npcs.json", ROOT / "config/wasm/events.json"
    npcs = [npc for npc in json.loads(npcs_path.read_text(encoding="utf-8")) if npc.get("module") != MODULE]
    events = {label: entry for label, entry in json.loads(events_path.read_text(encoding="utf-8")).items() if not (isinstance(entry, dict) and entry.get("module") == MODULE)}
    maps = {path.stem.lower() for path in (ROOT / "config/maps/pre-re").glob("*.mcache")}
    taken = {npc["name"] for npc in npcs}
    placed = 0
    for _, definition in definitions:
        key = definition.name if definition.kind == "script" else definition.source
        if key not in routes or definition.place is None:
            continue
        source_definition, labels = routes[key]
        map_name, x, y, direction = definition.place
        if map_name.lower() not in maps:
            skipped.append(f"{definition.name} (no map cache for {map_name})")
            continue
        if definition.name in taken:
            skipped.append(f"{definition.name} (name already taken)")
            continue
        taken.add(definition.name)
        trigger = definition.trigger or source_definition.trigger or (0, 0)
        sprite = "111" if definition.sprite in ("-1", "FAKE_NPC") else definition.sprite
        npcs.append(dict(map_name=map_name, x=x, y=y, dir=direction, name=definition.name, sprite=sprite, x_size=trigger[0], y_size=trigger[1],
                         constructor_args=[], module=MODULE, entry=key))
        for label in (label for label in labels if label.startswith("On")):
            events.setdefault(f"{definition.name}::{event_name(labels, label)}", {"module": MODULE, "entry": f"{key}::{label}"})
        placed += 1
    npcs_path.write_text(json.dumps(npcs, indent=2) + "\n", encoding="utf-8")
    events_path.write_text(json.dumps(events, indent=2) + "\n", encoding="utf-8")
    print(f"wrote scripts/towns/{MODULE}: {len(scripts)} scripts, {placed} placements")
    for reason in skipped:
        print(f"  skipped {reason}")


if __name__ == "__main__":
    main()
