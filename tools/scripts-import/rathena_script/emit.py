"""Writes the generated Rust modules and the NPC and event registries."""

import collections
import json
import re

from .codegen import rust_string

FIRST_NPC_ENTRY = 10_000
FIRST_EVENT_ENTRY = 100_000
SHOP_ENTRY = 6
# NPCs without a map (`-	script	Name	-1,{`) run event controllers: they stand invisible in a corner of this map
FLOATING_PLACE = ("prontera", 1, 1, 0)
HEADER = """// Generated by tools/scripts-import/convert_npcs.py from {source}. Do not edit.
#![allow(non_snake_case, unused_labels, unused_parens, unused_mut, unused_variables, unused_assignments, unreachable_code, unused_imports, dead_code, clippy::all)]
use script_sdk::{{Context, Function, Value}};
use crate::rt::*;
"""


def referenced_labels(scripts):
    """Labels other scripts name in a string such as `"Name::OnLabel"`."""
    return set()


def event_labels(script):
    return [label for label in script.labels if label.startswith("On")]


def event_name(script, label):
    """The engine fires `OnTouch` for the touch area; `OnTouch_` is the same trigger in rathena."""
    if label == "OnTouch_" and "OnTouch" not in script.labels:
        return "OnTouch"
    return label


def write_outputs(root, definitions, scripts, functions, routes=None):
    generated = root / "scripts/src/generated"
    generated.mkdir(parents=True, exist_ok=True)
    for stale in generated.glob("*.rs"):
        stale.unlink()

    by_name = {(s.exname or s.name): s for s in scripts if not s.blockers}
    modules = collections.OrderedDict()
    used_functions = set()
    for script in scripts:
        if not script.blockers:
            modules.setdefault(script.module, {"scripts": [], "functions": []})["scripts"].append(script)
    for script in scripts:
        if not script.blockers:
            used_functions.update(re.findall(r"super::(\w+)::(fn_\w+)", script.source))
    changed = True
    by_function_path = {(f.module, f.rust_name): f for f in functions if f.convertible}
    while changed:
        changed = False
        for key in list(used_functions):
            function = by_function_path.get(key)
            if function is None:
                continue
            for dependency in re.findall(r"super::(\w+)::(fn_\w+)", function.source):
                if dependency not in used_functions:
                    used_functions.add(dependency)
                    changed = True
    for module, rust_name in sorted(used_functions):
        function = by_function_path.get((module, rust_name))
        if function:
            modules.setdefault(module, {"scripts": [], "functions": []})["functions"].append(function)

    events = {}
    next_event = FIRST_EVENT_ENTRY
    npcs = []
    event_entries = {}
    for module, content in modules.items():
        dispatch_npc, dispatch_event = [], []
        sources = sorted({d.file for d in content["scripts"] + content["functions"]})
        body = [HEADER.format(source=", ".join(sources))]
        for function in content["functions"]:
            body.append(function.source.replace("fn ", "pub(crate) fn ", 1))
        for script in content["scripts"]:
            body.append(script.source)
            dispatch_npc.append(f"        {script.entry_id} => npc_call({script.rust_name}(ctx, 0, vec![])),")
            for label in event_labels(script):
                event_entries[(script.name, label)] = next_event
                dispatch_event.append(f"        {next_event} => npc_call({script.rust_name}(ctx, {script.labels[label]}, vec![])),")
                next_event += 1
        body.append("fn npc_call(result: Result<Value, String>) -> Option<Result<(), String>> {\n    Some(finish(result))\n}")
        body.append("pub fn run_npc(ctx: &Context, id: u32) -> Option<Result<(), String>> {\n    match id {\n" + "\n".join(dispatch_npc) + "\n        _ => None,\n    }\n}")
        body.append("pub fn run_event(ctx: &Context, id: u32) -> Option<Result<(), String>> {\n    match id {\n" + "\n".join(dispatch_event) + "\n        _ => None,\n    }\n}")
        (generated / f"{module}.rs").write_text("\n\n".join(body) + "\n", encoding="utf-8")

    mod_lines = ["// Generated by tools/scripts-import/convert_npcs.py. Do not edit.", ""]
    mod_lines += [f"mod {module};" for module in modules]
    mod_lines += ["", "use script_sdk::Context;", ""]
    for kind in ("npc", "event"):
        mod_lines.append(f"pub fn run_{kind}(ctx: &Context, id: u32) -> Option<Result<(), String>> {{")
        mod_lines.append("    None")
        for module in modules:
            mod_lines.append(f"        .or_else(|| {module}::run_{kind}(ctx, id))")
        mod_lines.append("}")
        mod_lines.append("")
    (generated / "mod.rs").write_text("\n".join(mod_lines), encoding="utf-8")

    write_registries(root, definitions, scripts, by_name, event_entries, routes)


def shop_arguments(definition):
    """Constructor arguments of the shop NPC (entry 6): the shop kind, then item and price pairs; a price of -1 keeps the item's own."""
    arguments = [{"Number": 0}]
    for specification in definition.details.split(","):
        item, _, price = specification.strip().partition(":")
        arguments += [{"Number": int(item)}, {"Number": int(price)}]
    return arguments


SCRIPT_WARPS = "config/npc/pre-re/warps/script_warps.txt"
# Legacy entry ids of the NPCs moved to named modules, for the trace comparison between the two
MIGRATION_MAP = "config/wasm/migration_map.json"
WARP_CONF = "config/npc/scripts_warps.conf"


def write_script_warps(root, definitions, maps):
    """The `warp` lines that live inside script files, in the format the warp loader reads; both ends need a map cache."""
    lines = ["// Generated by tools/scripts-import/convert_npcs.py from the warp definitions inside NPC scripts. Do not edit."]
    seen, dropped = set(), 0
    for definition in definitions:
        if definition.kind != "warp" or definition.place is None:
            continue
        map_name, x, y, direction = definition.place
        fields = definition.details.split(",")
        if len(fields) != 4 or map_name.lower() not in maps or fields[1].lower() not in maps or definition.name in seen:
            dropped += 1
            continue
        seen.add(definition.name)
        lines.append(f"{map_name},{x},{y},{direction}\twarp\t{definition.name}\t{definition.sprite},{definition.details}")
    (root / SCRIPT_WARPS).write_text("\n".join(lines) + "\n", encoding="utf-8")
    conf = root / WARP_CONF
    entry = "npc: " + SCRIPT_WARPS.split("config/npc/")[1]
    text = conf.read_text(encoding="utf-8")
    if entry not in text:
        conf.write_text(text.rstrip("\n") + "\n\n// Warps defined inside script files\n" + entry + "\n", encoding="utf-8")
    print(f"wrote {len(lines) - 1} script warps, dropped {dropped} (map without a cache)")


def write_registries(root, definitions, scripts, by_name, event_entries, routes=None):
    """Rewrites the NPC and event manifests. `routes` maps `(file, line)` of a script to `(module, key)` for the scripts sdk-2 converts;
    those are dispatched by name, every other script by its legacy `entry_id`."""
    routes = routes or {}
    npcs_path = root / "config/wasm/npcs.json"
    events_path = root / "config/wasm/events.json"
    # Generated shops share entry 6 with the hand-written ones but are the only ones with a trigger area; named entries are regenerated
    npcs = [npc for npc in json.loads(npcs_path.read_text(encoding="utf-8")) if "module" not in npc and npc["entry_id"] < FIRST_NPC_ENTRY and not (npc["entry_id"] == SHOP_ENTRY and "x_size" in npc)]
    events = {label: entry for label, entry in json.loads(events_path.read_text(encoding="utf-8")).items() if isinstance(entry, int) and entry < FIRST_EVENT_ENTRY}
    routed_by_name = {(d.exname or d.name): d for d in definitions if d.kind == "script" and not d.error and (d.file, d.line) in routes}
    placed = 0
    taken = {npc["name"] for npc in npcs}
    skipped, renamed, missing_maps = [], [], collections.Counter()
    maps = {path.stem.lower() for path in (root / "config/maps/pre-re").glob("*.mcache")}
    registered = []
    for definition in definitions:
        if definition.kind == "shop" and definition.place is not None and not definition.error:
            try:
                source, constructor_args, entry_id, trigger = definition, shop_arguments(definition), SHOP_ENTRY, (0, 0)
            except ValueError:
                print(f"skipped shop {definition.name}: unsupported item list {definition.details[:60]!r}")
                continue
        elif definition.kind in ("script", "duplicate") and definition.name:
            routed = definition.kind == "script" and (definition.file, definition.line) in routes
            if definition.kind == "script":
                source = definition if not definition.error and (routed or not definition.blockers) else None
            else:
                source = routed_by_name.get(definition.source) or by_name.get(definition.source)
            constructor_args, trigger = [], None
            if source is None:
                continue
            entry_id, trigger = source.entry_id, definition.trigger or source.trigger or (0, 0)
        else:
            continue
        map_name, x, y, direction = definition.place or FLOATING_PLACE
        if map_name.lower() not in maps:
            missing_maps[map_name] += 1
            continue
        name = definition.name
        if name in taken:
            # rathena only warns about two NPCs with one name; ours are keyed by name, so the later one gets a position suffix (same display name)
            name = f"{name.split('#')[0]}#{map_name}_{x}_{y}"
            if name in taken:
                skipped.append(definition.name)
                continue
            renamed.append(name)
        taken.add(name)
        route = routes.get((source.file, source.line)) if definition.kind != "shop" else None
        sprite = "111" if definition.sprite in ("-1", "FAKE_NPC") else definition.sprite
        placement = dict(map_name=map_name, x=x, y=y, dir=direction, name=name, sprite=sprite, **({} if route else {"entry_id": entry_id}),
                         x_size=trigger[0], y_size=trigger[1], constructor_args=constructor_args)
        if route:
            placement.update(module=route[0], entry=route[1])
        npcs.append(placement)
        registered.append((name, definition, source))
        placed += 1
    migration = {}
    for name, definition, source in registered:
        if definition.kind != "shop":
            route = routes.get((source.file, source.line))
            for label in event_labels(source):
                key = f"{name}::{event_name(source, label)}"
                if route:
                    events.setdefault(key, {"module": route[0], "entry": f"{route[1]}::{label}"})
                else:
                    events.setdefault(key, event_entries[(source.name, label)])
            if route:
                migration[name] = {
                    "entry_id": source.entry_id,
                    "events": {f"{name}::{event_name(source, label)}": event_entries[(source.name, label)] for label in event_labels(source)},
                }
    write_script_warps(root, definitions, maps)
    npcs_path.write_text(json.dumps(npcs, indent=2) + "\n", encoding="utf-8")
    events_path.write_text(json.dumps(events, indent=2) + "\n", encoding="utf-8")
    (root / MIGRATION_MAP).write_text(json.dumps(migration, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if renamed:
        print(f"renamed {len(renamed)} NPCs whose name was already taken: {renamed[:3]}")
    if skipped:
        print(f"skipped {len(skipped)} NPCs whose name is already taken: {skipped[:5]}")
    if missing_maps:
        print(f"skipped {sum(missing_maps.values())} NPCs on {len(missing_maps)} maps without a map cache: {', '.join(f'{name} ({count})' for name, count in missing_maps.most_common(60))}")
    print(f"wrote {placed} NPC placements and {len(event_entries)} event entry points")
